#!/usr/bin/env python3
"""rps_repair.py — certificate-guided repair in hidden-type Rock-Paper-Scissors.

The base learner is a small GRU trained on the histories generated by the COPY
teacher (every learner action tried), labelled with the exact Bayes-optimal
action for that history.  Because COPY's actions are a function of the
learner's own past actions, this state distribution never contains a teacher
opening with Paper or Scissors, and it never shows the learner how to react to
a teacher that departs from copying.  The exact certificate exposes those
failures; CGR adds only the violating frontier histories and refits.

Baselines, all with the same per-round added-state budget, optimizer and
stopping rule:
  * control pools  copy / all / opt   — random states, no look at violations
  * dagger-all                        — random states from the learner's own
                                        rollouts against the uniform type prior
  * dagger-worst                      — rollouts against the worst-scoring type

Usage:
  python src/rps_repair.py --seed 0 --max-iters 20 \
      --ckpt-out runs/rps_s0 --out data/rps_s0.json
"""
from __future__ import annotations

import argparse
import json
import pathlib
import random
import statistics
import time
from datetime import datetime, timezone
from itertools import accumulate

import torch
import torch.nn as nn

import rps_game as g

ROOT = pathlib.Path(__file__).resolve().parent.parent
START, PAD, VOCAB = 6, 7, 8


class GRUPolicy(nn.Module):
    def __init__(self, hidden: int = 64, emb: int = 8) -> None:
        super().__init__()
        self.emb = nn.Embedding(VOCAB, emb, padding_idx=PAD)
        self.gru = nn.GRU(emb, hidden, batch_first=True)
        self.head = nn.Linear(hidden, g.N_ACTIONS)

    def forward(self, tokens, lengths):
        e = self.emb(tokens)
        packed = nn.utils.rnn.pack_padded_sequence(
            e, lengths.cpu(), batch_first=True, enforce_sorted=False)
        _, h = self.gru(packed)
        return self.head(h[-1])

    @staticmethod
    def encode(history: tuple) -> list[int]:
        seq = [START]
        for l, t in history:
            seq.append(int(l))
            seq.append(3 + int(t))
        return seq

    @torch.no_grad()
    def act(self, history: tuple) -> int:
        seq = self.encode(history)
        toks = torch.tensor([seq], dtype=torch.long)
        lens = torch.tensor([len(seq)])
        return int(self.forward(toks, lens)[0].argmax())


def items_from(histories, oracle) -> list[dict]:
    out = []
    for h in histories:
        h = tuple(h)
        if len(h) >= oracle.horizon:
            continue
        opts = oracle.optimal(h)
        target = torch.zeros(g.N_ACTIONS)
        for a in opts:
            target[a] = 1.0 / len(opts)
        out.append({"history": h, "target": target, "optimal": set(opts)})
    return out


def _batched(items, batch_size):
    seqs = [GRUPolicy.encode(it["history"]) for it in items]
    order = sorted(range(len(items)), key=lambda i: -len(seqs[i]))
    for i in range(0, len(items), batch_size):
        idx = order[i:i + batch_size]
        maxlen = max(len(seqs[j]) for j in idx)
        toks = torch.full((len(idx), maxlen), PAD, dtype=torch.long)
        lens = torch.tensor([len(seqs[j]) for j in idx], dtype=torch.long)
        for r, j in enumerate(idx):
            toks[r, :len(seqs[j])] = torch.tensor(seqs[j])
        yield idx, toks, lens


@torch.no_grad()
def predict_all(policy, items, batch_size: int = 512) -> list[int]:
    policy.eval()
    acts = [0] * len(items)
    for idx, toks, lens in _batched(items, batch_size):
        pred = policy(toks, lens).argmax(-1).tolist()
        for r, j in enumerate(idx):
            acts[j] = int(pred[r])
    return acts


def all_optimal(policy, items) -> bool:
    if not items:
        return True
    return all(a in it["optimal"]
               for a, it in zip(predict_all(policy, items), items))


def n_optimal_mistakes(policy, items) -> int:
    if not items:
        return 0
    return sum(1 for a, it in zip(predict_all(policy, items), items)
               if a not in it["optimal"])


def fit(policy, items, epochs, lr, seed, stop_items=None, log=print):
    if not items:
        return 0.0, 0
    opt = torch.optim.Adam(policy.parameters(), lr=lr)
    rng = random.Random(seed)
    policy.train()
    last = 0.0
    for ep in range(epochs):
        shuffled = items[:]
        rng.shuffle(shuffled)
        total, nb = 0.0, 0
        for idx, toks, lens in _batched(shuffled, 256):
            logits = policy(toks, lens)
            targets = torch.stack([shuffled[j]["target"] for j in idx])
            loss = -(targets * torch.log_softmax(logits, dim=-1)).sum(dim=-1).mean()
            opt.zero_grad()
            loss.backward()
            opt.step()
            total += float(loss.detach())
            nb += 1
        last = total / max(1, nb)
        if stop_items is not None and all_optimal(policy, stop_items):
            return last, ep + 1
    return last, epochs


def sample_pool(pool, k, rng, used) -> list:
    if k <= 0:
        return []
    avail = [h for h in pool if h not in used]
    if len(avail) <= k:
        return avail
    return rng.sample(avail, k)


_HISTORIES: dict[int, list] = {}


def _reachable(horizon: int) -> list:
    if horizon not in _HISTORIES:
        _HISTORIES[horizon] = [h for h in g.all_histories(horizon)
                               if len(h) < horizon]
    return _HISTORIES[horizon]


def action_map(policy, oracle) -> dict:
    """Batched action for every reachable history (one forward pass set)."""
    hist = _reachable(oracle.horizon)
    acts = predict_all(policy, [{"history": h} for h in hist])
    return dict(zip(hist, acts))


def certify(policy, oracle):
    return g.certificate(None, oracle, action_map(policy, oracle))


def cert_row(cert, extra=None) -> dict:
    row = {
        "value": cert["value"],
        "bayes_value": cert["bayes_value"],
        "normalized": cert["normalized"],
        "n_frontier": cert["n_frontier"],
        "n_violations": cert["n_violations"],
        "per_type": cert["per_type"],
    }
    if extra:
        row.update(extra)
    return row


def rollout_histories(policy, types, horizon) -> set:
    out = set()
    for t in types:
        h = ()
        while len(h) < horizon:
            a = policy.act(h)
            ta = g.teacher_action(t, h)
            h = h + ((a, ta),)
            if len(h) < horizon:
                out.add(h)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--horizon", type=int, default=8)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--emb", type=int, default=8)
    ap.add_argument("--epochs", type=int, default=120)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--agg-repeat", type=int, default=40)
    ap.add_argument("--max-iters", type=int, default=20)
    ap.add_argument("--threads", type=int, default=2)
    ap.add_argument("--control-seeds", default="1,2,3")
    ap.add_argument("--control-mode", default="copy,all,opt")
    ap.add_argument("--control-epochs", type=int, default=0,
                    help="per-round epoch cap for controls; 0 uses --epochs")
    ap.add_argument("--dagger-seeds", default="1,2,3")
    ap.add_argument("--dagger-mode", default="all,worst")
    ap.add_argument("--no-controls", action="store_true")
    ap.add_argument("--no-dagger", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "data" / "rps.json"))
    ap.add_argument("--ckpt-out", default="")
    args = ap.parse_args()
    torch.set_num_threads(args.threads)

    t_start = time.time()
    oracle = g.Oracle(args.horizon)
    vstar = oracle.value(())
    vmin = oracle.value_min(())
    print(f"horizon {args.horizon} V* {vstar:.4f} Vmin {vmin:.4f} "
          f"span {vstar - vmin:.4f} states {len(g.all_histories(args.horizon))}",
          flush=True)

    replay_hist = [h for h in g.copy_tree(args.horizon)
                   if len(h) < args.horizon]
    replay = items_from(replay_hist, oracle)
    print(f"replay histories {len(replay_hist)} items {len(replay)}", flush=True)

    torch.manual_seed(args.seed)
    policy = GRUPolicy(args.hidden, args.emb)
    t0 = time.time()
    loss, eps = fit(policy, replay, args.epochs, args.lr, args.seed,
                    stop_items=replay)
    base_cert = certify(policy, oracle)
    base_mistakes = n_optimal_mistakes(policy, replay)
    print(f"base loss {loss:.4f} epochs {eps} replay_mistakes {base_mistakes} "
          f"| V {base_cert['value']:.3f} W {base_cert['normalized']:.3f} "
          f"frontier {base_cert['n_frontier']} viol {base_cert['n_violations']} "
          f"per-type {base_cert['per_type']} [{time.time()-t0:.0f}s]", flush=True)

    base_state = {k: v.clone() for k, v in policy.state_dict().items()}

    # ---- repair arm ----
    agg: list[tuple] = []
    agg_set: set[tuple] = set()
    cgr_log: list[dict] = []
    cgr_adds: list[int] = []
    t0 = time.time()
    for it in range(args.max_iters):
        cert = certify(policy, oracle)
        row = cert_row(cert, {"round": it, "aggregate": len(agg)})
        if cert["normalized"] >= 1.0 - 1e-9:
            row["added_after"] = 0
            cgr_log.append(row)
            print(f"[cgr {it:2d}] certified W=1", flush=True)
            break
        new = [v["history"] for v in cert["violations"]
               if tuple(v["history"]) not in agg_set]
        row["added_after"] = len(new)
        cgr_log.append(row)
        print(f"[cgr {it:2d}] V {cert['value']:7.3f} W {cert['normalized']:.3f} "
              f"frontier {cert['n_frontier']:3d} viol {cert['n_violations']:3d} "
              f"add {len(new):3d} agg {len(agg):3d} "
              f"per-type {cert['per_type']}", flush=True)
        if not new:
            print("no new violating histories; stopping", flush=True)
            break
        for h in new:
            agg.append(tuple(h))
            agg_set.add(tuple(h))
        cgr_adds.append(len(new))
        agg_items = items_from(agg, oracle)
        stop = replay + agg_items
        l, e = fit(policy, replay + agg_items * args.agg_repeat,
                   args.epochs, args.lr, args.seed + 1 + it, stop_items=stop)
        print(f"    fit loss {l:.4f} epochs {e} "
              f"agg_mistakes {n_optimal_mistakes(policy, agg_items)} "
              f"[{time.time()-t0:.0f}s]", flush=True)
    repair_s = time.time() - t0
    final_cert = certify(policy, oracle)
    print(f"repair final V {final_cert['value']:.3f} W {final_cert['normalized']:.3f} "
          f"added {len(agg)} rounds {len(cgr_adds)} per-type {final_cert['per_type']} "
          f"[{repair_s:.0f}s]", flush=True)

    ckpt_path = ""
    if args.ckpt_out:
        p = pathlib.Path(args.ckpt_out)
        p.mkdir(parents=True, exist_ok=True)
        f = p / "rps_gru.pt"
        torch.save(policy.state_dict(), str(f))
        ckpt_path = str(f)
        print(f"saved {f}", flush=True)

    counts = list(accumulate(cgr_adds))
    modes = [m.strip() for m in args.control_mode.split(",") if m.strip()]

    pools: dict[str, list] = {}
    if "copy" in modes:
        pools["copy"] = [h for h in g.copy_tree(args.horizon)
                         if len(h) < args.horizon]
    if "all" in modes:
        pools["all"] = [h for h in g.all_histories(args.horizon)]
    if "opt" in modes:
        pools["opt"] = [h for h in g.optimal_tree(oracle, args.horizon)
                        if len(h) < args.horizon]
    print("pools " + " ".join(f"{k}={len(v)}" for k, v in pools.items()), flush=True)

    controls = []
    if not args.no_controls and counts:
        for mode in modes:
            for cseed in [int(s) for s in args.control_seeds.split(",") if s.strip()]:
                torch.manual_seed(1000 + cseed)
                c_policy = GRUPolicy(args.hidden, args.emb)
                c_policy.load_state_dict(base_state)
                rng = random.Random(10_000 + cseed)
                pool = pools[mode]
                c_agg, c_set = [], set()
                c_log = [cert_row(base_cert, {"round": 0, "added": 0})]
                t0c = time.time()
                for r, target in enumerate(counts):
                    need = target - len(c_agg)
                    for h in sample_pool(pool, need, rng, c_set):
                        c_agg.append(h)
                        c_set.add(h)
                    c_items = items_from(c_agg, oracle)
                    l, e = fit(c_policy, replay + c_items * args.agg_repeat,
                               args.control_epochs or args.epochs, args.lr,
                               args.seed + 100 + r + cseed,
                               stop_items=replay + c_items)
                    cert = certify(c_policy, oracle)
                    c_log.append(cert_row(cert, {
                        "round": r + 1, "added": len(c_agg), "epochs": e,
                        "replay_mistakes": n_optimal_mistakes(c_policy, replay),
                    }))
                    print(f"  control {mode} s{cseed} {r+1}/{len(counts)}: "
                          f"W {cert['normalized']:.3f} added {len(c_agg)} "
                          f"epochs {e} [{time.time()-t0c:.0f}s]", flush=True)
                controls.append({
                    "pool": mode, "seed": cseed, "log": c_log,
                    "final": c_log[-1], "elapsed_s": time.time() - t0c,
                })
                print(f"control {mode} s{cseed}: W {c_log[-1]['normalized']:.3f} "
                      f"added {c_log[-1]['added']} "
                      f"per-type {c_log[-1]['per_type']}", flush=True)

    daggers = []
    dm = [m.strip() for m in args.dagger_mode.split(",") if m.strip()]
    if not args.no_dagger and counts:
        for mode in dm:
            for dseed in [int(s) for s in args.dagger_seeds.split(",") if s.strip()]:
                torch.manual_seed(2000 + dseed)
                d_policy = GRUPolicy(args.hidden, args.emb)
                d_policy.load_state_dict(base_state)
                rng = random.Random(20_000 + dseed)
                d_agg, d_set = [], set()
                d_log = [cert_row(base_cert, {"round": 0, "added": 0})]
                t0d = time.time()
                for r, target in enumerate(counts):
                    if mode == "worst":
                        pts = g.per_type(lambda h: d_policy.act(h), args.horizon)
                        worst = min(range(g.N_TYPES), key=lambda k: pts[k])
                        visited = rollout_histories(d_policy, [worst], args.horizon)
                    else:
                        visited = rollout_histories(d_policy, range(g.N_TYPES),
                                                    args.horizon)
                    new = [h for h in visited if h not in d_set]
                    need = target - len(d_agg)
                    chosen = rng.sample(new, min(need, len(new))) if new else []
                    for h in chosen:
                        d_agg.append(h)
                        d_set.add(h)
                    d_items = items_from(d_agg, oracle)
                    l, e = fit(d_policy, replay + d_items * args.agg_repeat,
                               args.epochs, args.lr,
                               args.seed + 200 + r + dseed,
                               stop_items=replay + d_items)
                    cert = certify(d_policy, oracle)
                    d_log.append(cert_row(cert, {
                        "round": r + 1, "added": len(d_agg), "epochs": e,
                        "visited": len(visited),
                    }))
                    print(f"  dagger-{mode} s{dseed} {r+1}/{len(counts)}: "
                          f"W {cert['normalized']:.3f} added {len(d_agg)} "
                          f"visited {len(visited)} epochs {e} "
                          f"[{time.time()-t0d:.0f}s]", flush=True)
                daggers.append({
                    "pool": f"dagger-{mode}", "seed": dseed, "log": d_log,
                    "final": d_log[-1], "elapsed_s": time.time() - t0d,
                })
                print(f"dagger-{mode} s{dseed}: W {d_log[-1]['normalized']:.3f} "
                      f"added {d_log[-1]['added']} "
                      f"per-type {d_log[-1]['per_type']}", flush=True)

    out = {
        "args": vars(args),
        "environment": {
            "python": __import__("platform").python_version(),
            "torch": torch.__version__,
            "when_utc": datetime.now(timezone.utc).isoformat(),
        },
        "game": {
            "horizon": args.horizon,
            "types": list(g.TYPE_NAMES),
            "bayes_value": vstar,
            "min_value": vmin,
            "span": vstar - vmin,
            "n_histories": len(g.all_histories(args.horizon)),
        },
        "replay": {"histories": len(replay_hist), "items": len(replay)},
        "base": {"certificate": base_cert, "fit_loss": loss, "fit_epochs": eps,
                 "replay_mistakes": base_mistakes},
        "repair": {"log": cgr_log, "final": final_cert, "aggregate": agg,
                   "adds": cgr_adds, "checkpoint": ckpt_path,
                   "elapsed_s": repair_s},
        "controls": controls,
        "dagger": daggers,
        "elapsed_s": time.time() - t_start,
    }
    p = pathlib.Path(args.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(f"wrote {p}", flush=True)


if __name__ == "__main__":
    main()
